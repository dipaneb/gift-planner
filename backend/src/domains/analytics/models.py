import uuid
from datetime import datetime

from sqlalchemy import Boolean, DateTime, Index, String
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column

from src.infrastructure.database.base import Base


class Visit(Base):
    """One visit = one browser session landing on the site."""
    __tablename__ = "visits"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )

    # True when the visitor came through the link printed on the CV (?ref=cv)
    from_cv: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        default=False,
    )

    # Random id generated by the browser and kept in localStorage, used to count
    # unique visitors without storing any IP address.
    visitor_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        nullable=False,
    )

    user_agent: Mapped[str | None] = mapped_column(
        String(512),
    )

    __table_args__ = (
        Index("idx_visits_created_at", "created_at"),
    )


class WeeklyReport(Base):
    """Marks a weekly report as sent, so it is never sent twice (restarts, several workers)."""
    __tablename__ = "weekly_reports"

    # Scheduled sending time of the report (UTC). Also the end of the reported period.
    period_end: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        primary_key=True,
    )
